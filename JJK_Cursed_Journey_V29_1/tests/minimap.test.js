'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const src = fs.readFileSync(require('node:path').join(__dirname,'../public/rpg.js'),'utf8');
const begin=src.indexOf('const MINIMAP_THEMES=');
const end=src.indexOf('let frame=0;',begin);
assert.ok(begin>=0 && end>begin,'region-aware minimap palette must be present');
const shader=src.slice(begin,end);
const colors=vm.runInNewContext('(()=>{const state={zone:0};'+shader+';return Array.from({length:7},(_,zone)=>Array.from({length:8},(_,tile)=>minimapTileColor(tile+1,zone)));})()');
assert.equal(colors.length,7);
assert.equal(new Set(colors.map(z=>z[0])).size,7,'each region needs unique ground color');
assert.equal(colors[0][0],'#4c6857','the school is green');
assert.equal(colors[6][0],'#4c2c3e','the final shrine is red-purple, not green');
assert.equal(colors[5][0],'#635157','Shinjuku ruins use ash-colored terrain');
assert.ok(src.includes('rect(mx+xx*ms,my+yy*ms,2,2,minimapTileColor(tt,stage))'),'HUD minimap uses live stage');
assert.ok(src.includes('ctx.fillStyle=minimapTileColor(tile,state.zone)'),'atlas uses the active stage');
assert.ok(src.includes("write(Z[stage].name.toUpperCase()"),'HUD minimap title uses active region name');
console.log('PASS live 7-region minimap colors and atlas stage rendering');
